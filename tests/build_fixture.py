def build(root):
    subprocess.run([sys.executable, os.path.join(TOOLS, "new_project.py"), "测试书",
                    "--genre", "末世丧尸", "--chapter-words", "110",
                    "--daily", "2", "--root", root], check=True, capture_output=True)
    base = os.path.join(root, "测试书")
    w = lambda rel, t: open(os.path.join(base, rel), "w", encoding="utf-8").write(t)

    w("设定/世界观.md", "# 世界观\n\n## 规则\n1. 感染经体液传播，潜伏 6 小时。\n2. 停电后第 3 天停水。\n3. 声音会吸引感染体。\n")
    w("设定/人设.md", "# 人物\n\n## 主角\n- 姓名：林晚\n- 外在目标：活到救援\n- 内在缺口：怕独处\n- 说话习惯：短句，不说软话\n\n## 主要配角\n| 姓名 | 功能位 | 与主角关系 | 自身目标 | 结局走向 |\n|---|---|---|---|---|\n| 老周 | 邻居 | 对门 | 找女儿 | 早死留线索 |\n")
    w("大纲/00-总纲.md", "# 总纲\n\n## 主线里程碑\n1. 熬过停电第一夜\n2. 离开本楼\n3. 找到城外营地\n## 分卷规划\n| 卷 | 章节范围 | 卷目标 | 卷末转折 |\n|---|---|---|---|\n| 一 | 1-20 | 逃出楼 | 老周变异 |\n")
    w("大纲/10-卷纲-卷一.md", "# 卷一 卷纲\n\n- 章节范围：1-20\n## 本卷目标\n逃出这栋楼。\n## 主要事件链（按章）\n1. 楼道断电，林晚确认外面异常\n2. 老周家门缝有异动，林晚决定观察\n3. 楼下传来枪声，林晚决定下楼\n")
    for n, d in PLAN.items():
        w(f"大纲/细纲/第{n:03d}章.md",
          f"# 第{n:03d}章\n\n- 目标: {d['goal']}\n- 冲突: 不敢出门又必须出门\n"
          f"- 信息增量: 感染体靠声音定位\n- 出场: 林晚、老周\n- 钩子: 悬念\n- 字数: 110\n- 功能: {['推进','铺垫','爽点'][n-1]}\n\n## 要点\n"
          + "\n".join(f"{i}. {p}" for i, p in enumerate(d["points"], 1)) + "\n")
    for n, t in CH.items():
        w(f"正文/第{n:03d}章-{'停电' if n==1 else ('门缝' if n==2 else '枪声')}.md", t)
    w("追踪/伏笔.md", "# 伏笔台账\n\n| 编号 | 埋设章 | 内容 | 指向 | 计划回收章 | 状态 |\n|---|---|---|---|---|---|\n"
      "| F001 | 1 | 走廊拖拽声 | 感染源 | 9 | 未回收 |\n")
    w("追踪/状态.md", "# 状态\n\n| 章节 | 时间点 | 地点 | 在场人物 | 关键物 | 未结事项 |\n|---|---|---|---|---|---|\n"
      "| 3 | 停电第1天 21:10 | 5楼走廊 | 林晚 | 菜刀 | 走廊尽头有人影 |\n")
